class MultiScaleEncoder_Disen(nn.Module):
    def __init__(self,
                 in_channel,
                 max_depth,
                 input_res=256,
                 channel_query_dict=None,
                 norm_type='gn',
                 act_type='leakyrelu',
                 LQ_stage=True,
                 **swin_opts,
                 ):
        super().__init__()

        ksz = 3

        self.in_conv = nn.Conv2d(in_channel, channel_query_dict[input_res], 4, padding=1)

        self.blocks = nn.ModuleList()
        self.up_blocks = nn.ModuleList()
        self.max_depth = max_depth
        res = input_res
        for i in range(max_depth):
            in_ch, out_ch = channel_query_dict[res], channel_query_dict[res // 2]
            tmp_down_block = [
                nn.Conv2d(in_ch, out_ch, ksz, stride=2, padding=1),
                ResBlock(out_ch, out_ch, norm_type, act_type),
                ResBlock(out_ch, out_ch, norm_type, act_type),
            ]
            self.blocks.append(nn.Sequential(*tmp_down_block))
            res = res // 2

        if LQ_stage:
            self.swin = SwinLayers(**swin_opts)
            tt = input_res // 2**self.max_depth
            ch_fuse = channel_query_dict[tt]
            self.disen_conv = nn.Conv2d(ch_fuse, ch_fuse*2, 1)
            upsampler = nn.ModuleList()
            for i in range(2):
                in_channel, out_channel = channel_query_dict[res], channel_query_dict[res * 2]
                upsampler.append(nn.Sequential(
                    nn.Upsample(scale_factor=2),
                    nn.Conv2d(in_channel, out_channel, 3, stride=1, padding=1),
                    ResBlock(out_channel, out_channel, norm_type, act_type),
                    ResBlock(out_channel, out_channel, norm_type, act_type),
                    )
                )
                res = res * 2

            self.upsampler = upsampler

        self.LQ_stage = LQ_stage

    def forward(self, input):
        outputs = []
        # print(input.shape)
        x = self.in_conv(input)

        for idx, m in enumerate(self.blocks):
            x = m(x)
            outputs.append(x)

        feat_c = outputs[::-1]
        feat_ab = outputs[::-1]

        if self.LQ_stage:
            after_swin = self.swin(x)
            outputs.append(after_swin)
            # feat_FA = after_swin
            before_split_feat = self.disen_conv(after_swin)
            _, C, _, _ = before_split_feat.shape
            feat_c, feat_ab = torch.split(before_split_feat, C//2, dim=1)
            x = feat_c

            for idx, m in enumerate(self.upsampler):
                x = m(x)
                outputs.append(x)

        return outputs, feat_c, feat_ab



